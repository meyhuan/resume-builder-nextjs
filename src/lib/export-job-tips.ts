export function pickExportJobTips(random: () => number = Math.random) {
  const pool = [...EXPORT_JOB_TIPS]
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  return pool.slice(0, 5)
}
